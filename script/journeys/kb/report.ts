/**
 * docs/sky-journeys/kb-report.md generator for the KB build (script/journeys/build_kb.ts).
 * Pure: takes the merged KB plus the build log and returns Markdown. Deterministic (sorted everywhere, no dates).
 */
import {
  BATCH_IDS, EDGE_TYPES, FACT_KEYS, type ContextNode, type Edge, type FactKey, type KbObject, type NarrationBank, type Source,
} from '../../../client/src/lib/journeys/types';
import { byString, countBy } from './util';

export interface StorySeed {
  id: string; batch: string; kind: string; file: string; title: string; archetypes: string[]; stops: string[];
  optional?: string[]; summary?: string; sourceIds: string[]; extra?: Record<string, unknown>;
}

export interface BuildLog {
  inputs: { curated: string[]; auto: string[]; mediaAuto: string; mediaLicensed: string; mediaFill?: string };
  sourceRewrites: Record<string, number>;
  curatedFacts: Record<string, string[]>;
  sourceConflicts: { id: string; files: string[] }[];
  unreferencedSources: string[];
  magConflicts: { id: string; auto: number; curated: number }[];
  dropped: { id: string; what: string; why: string }[];
  notes: string[];
  autoOnly: string[];
  fixesApplied: { id: string; what: string; why: string }[];
  cardMissingFacts: { id: string; label: string; fact: string }[];
  comparisonRemaps: { id: string; label: string; from: string; to: string; why: string }[];
  images: {
    licensed: { id: string; src: string }[]; licensedSkipped: { id: string; src: string; reason: string }[];
    missingFile: { id: string; src: string }[]; remote: { id: string; src: string }[];
    filled: { id: string; src: string }[];
  };
  contexts: {
    merged: { id: string; files: string[] }[]; addedByFix: { id: string; member: string }[];
    unknownMembers: { id: string; member: string }[]; mirrored: { id: string; member: string; dir: string }[];
  };
  edges: {
    dropped: { edge: string; file: string; why: string }[];
    duplicates: { kept: string; removed: string[] }[];
    factRefsDropped: { edge: string; ref: string }[];
    losViolations: { edge: string; d1: number | null; d2: number | null }[];
    reasonFallbacks: { edge: string; from: string; to: string }[];
  };
  narration: { unioned: { key: string; file: string; variants: number }[]; added: string[]; pruned: string[] };
  seeds: { unknownStops: { seed: string; stop: string }[] };
}

export interface ReportInput {
  version: string;
  objects: KbObject[];
  contexts: ContextNode[];
  edges: Edge[];
  sources: Source[];
  narration: NarrationBank;
  seeds: StorySeed[];
  log: BuildLog;
  list: { id: string; name: string; batch: string; kind: string }[];
  eligible: (o: KbObject) => boolean;
  publicDir: string;
  auto: { dsoQa: { id: string; issue: string; detail: string }[]; starFlags: Record<string, string[]> };
}

const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : '–');
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(' | ')} |`, `|${head.map((_, i) => (i === 0 ? '---' : '---:')).join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const list = (xs: string[], empty = '_none_') => (xs.length ? xs.map((x) => `- ${x}`).join('\n') : empty);

function ineligibleReasons(o: KbObject): string[] {
  const r: string[] = [];
  const st = o.provenance?.status;
  if (st !== 'curated' && st !== 'reviewed') r.push(`status ${st ?? 'none'}${o.provenance?.ineligibleReason ? `: ${o.provenance.ineligibleReason}` : ''}`);
  if (!o.teaches.length) r.push('no teaches');
  if (!Object.values(o.facts).some((f) => f && Number.isFinite(f.value) && f.sourceId)) r.push('no sourced fact');
  const c = o.card;
  if (![c.glance, c.whyHere, c.see, c.understand, c.wonder, c.connect].every((x) => x && x.trim())) r.push('incomplete card');
  if (o.kind === 'dso' && o.view.basis === 'derived') r.push('binocular view still pipeline-derived');
  return r;
}

const UNCERTAIN = /verif|uncertain|disput|disagree|tension|debat|controvers|unclear|unknown|\?/i;

export function renderReport(R: ReportInput): string {
  const { objects, log } = R;
  const L: string[] = [];
  const stars = objects.filter((o) => o.kind === 'star');
  const dsos = objects.filter((o) => o.kind === 'dso');
  const elig = new Set(objects.filter(R.eligible).map((o) => o.id));
  const batchOf = (o: KbObject) => o.provenance?.batch ?? '?';

  L.push('# Sky Journeys knowledge base: build report', '');
  L.push(`Generated by \`npm run journeys:kb\` (script/journeys/build_kb.ts). Do not edit by hand. KB version \`${R.version}\`.`, '');
  L.push(`Inputs: ${log.inputs.curated.length} curated files (${log.inputs.curated.join(', ')}); auto tier ${log.inputs.auto.join(', ')}; media.auto ${log.inputs.mediaAuto}; media.licensed ${log.inputs.mediaLicensed}; media.fill ${log.inputs.mediaFill ?? 'absent'}.`, '');
  L.push('Outputs in `client/public/data/journeys/`: kb.json, edges.json, concepts.json, templates.json, narration.json, story-seeds.json. ' +
    'All of them pass `knowledgeBaseFromFiles()` (zod shape + referential checks) with zero issues; the build refuses to write otherwise.', '');

  // ── totals
  L.push('## Totals', '');
  L.push(table(['', 'count'], [
    ['objects', objects.length], ['… stars', stars.length], ['… deep-sky', dsos.length],
    ['journey-eligible objects', elig.size], ['context nodes', R.contexts.length], ['curated edges', R.edges.length],
    ['sources', R.sources.length], ['narration keys', Object.keys(R.narration.variants).length], ['story seeds', R.seeds.length],
  ]), '');

  // ── by batch / kind / tier
  L.push('## Objects by batch, kind and card tier', '');
  L.push(table(['batch', 'stars', 'dso', 'eligible stars', 'eligible dso', 'showpiece cards', 'supporting cards'], BATCH_IDS.map((b) => {
    const xs = objects.filter((o) => batchOf(o) === b);
    return [b, xs.filter((o) => o.kind === 'star').length, xs.filter((o) => o.kind === 'dso').length,
      xs.filter((o) => o.kind === 'star' && elig.has(o.id)).length, xs.filter((o) => o.kind === 'dso' && elig.has(o.id)).length,
      xs.filter((o) => o.card.tier === 'showpiece').length, xs.filter((o) => o.card.tier === 'supporting').length];
  })), '');
  L.push('### Deep-sky classes', '');
  L.push(table(['dsoClass', 'objects', 'eligible'], Array.from(countBy(dsos, (o) => (o.kind === 'dso' ? o.dsoClass : ''))).map(([k, n]) =>
    [k, n, dsos.filter((o) => o.kind === 'dso' && o.dsoClass === k && elig.has(o.id)).length])), '');
  L.push('### Stars by spectral class and evolutionary stage', '');
  L.push(table(['spectral class', 'stars'], Array.from(countBy(stars, (o) => (o.kind === 'star' ? o.spectral?.class ?? '(none)' : '')))), '');
  L.push(table(['evolutionaryStage', 'stars'], Array.from(countBy(stars, (o) => (o.kind === 'star' ? o.evolutionaryStage ?? '(none)' : '')))), '');
  L.push(table(['evoStage', 'objects'], Array.from(countBy(objects, (o) => String(o.evoStage)))), '');
  L.push('### Roles', '');
  const roleCounts = new Map<string, number>();
  for (const o of objects) for (const r of o.roles) roleCounts.set(r, (roleCounts.get(r) ?? 0) + 1);
  L.push(table(['role', 'objects'], Array.from(roleCounts.entries()).sort((a, b) => byString(a[0], b[0]))), '');

  // ── fact coverage
  L.push('## Fact coverage', '');
  L.push('Share of objects carrying each fact (any tier). "curated" counts values the curated tier supplied or replaced.', '');
  L.push(table(['fact', 'stars', '%', 'dso', '%', 'curated values', 'eligible objects with it'], FACT_KEYS.map((k: FactKey) => {
    const s = stars.filter((o) => o.facts[k]).length;
    const d = dsos.filter((o) => o.facts[k]).length;
    const cur = objects.filter((o) => o.facts[k] && (log.curatedFacts[o.id] ?? []).includes(k)).length;
    return [k, s, pct(s, stars.length), d, pct(d, dsos.length), cur, objects.filter((o) => o.facts[k] && elig.has(o.id)).length];
  })), '');
  const methods = countBy(objects.flatMap((o) => Object.values(o.facts).map((f) => f!.method)), (m) => m);
  L.push(`Fact methods: ${Array.from(methods).map(([m, n]) => `${m} ${n}`).join(' · ')}.`, '');

  // ── edges
  L.push('## Edges by type', '');
  L.push(table(['type', 'edges', 'undirected', 'mean strength', 'with factRefs'], EDGE_TYPES.map((t) => {
    const es = R.edges.filter((e) => e.type === t);
    const mean = es.length ? (es.reduce((a, e) => a + e.strength, 0) / es.length).toFixed(2) : '–';
    return [t, es.length, es.filter((e) => e.directed === false).length, mean, es.filter((e) => e.factRefs?.length).length];
  })), '');
  const degree = new Map<string, number>();
  for (const e of R.edges) for (const x of [e.from, e.to]) degree.set(x, (degree.get(x) ?? 0) + 1);
  const eligNoEdge = objects.filter((o) => elig.has(o.id) && !degree.get(o.id)).map((o) => o.id).sort(byString);
  L.push(`Eligible objects with no curated edge (they rely on derived edges at load): ${eligNoEdge.length}${eligNoEdge.length ? ` — ${eligNoEdge.join(', ')}` : ''}.`, '');
  L.push('### Duplicate edges removed', '');
  L.push(list(log.edges.duplicates.map((d) => `kept ${d.kept}; removed ${d.removed.join('; ')}`)), '');
  L.push('### LINE_OF_SIGHT edges without a distance ratio ≥ 2', '');
  L.push(list(log.edges.losViolations.map((v) => `${v.edge}: ${v.d1 ?? 'no distance'} ly vs ${v.d2 ?? 'no distance'} ly`)), '');
  if (log.edges.dropped.length || log.edges.factRefsDropped.length || log.edges.reasonFallbacks.length) {
    L.push('### Edge repairs', '');
    L.push(list([
      ...log.edges.dropped.map((d) => `dropped ${d.edge} (${d.file}): ${d.why}`),
      ...log.edges.factRefsDropped.map((d) => `${d.edge}: factRef ${d.ref} dropped (fact missing)`),
      ...log.edges.reasonFallbacks.map((d) => `${d.edge}: reasonKey ${d.from} missing → ${d.to}`),
    ]), '');
  }

  // ── eligibility per batch
  L.push('## Journey-eligible objects per batch', '');
  L.push('Gate (README, candidates.ts `isJourneyEligible`): curated/reviewed, ≥1 teaches, ≥1 sourced numeric fact, complete card, and for deep-sky objects a binocular view graded by a curator (not pipeline-derived).', '');
  for (const b of BATCH_IDS) {
    const xs = objects.filter((o) => batchOf(o) === b);
    const bad = xs.filter((o) => !elig.has(o.id));
    L.push(`- **${b}**: ${xs.length - bad.length}/${xs.length} eligible${bad.length ? `; not eligible: ${bad.map((o) => `${o.id} (${esc(ineligibleReasons(o).join('; '))})`).join(', ')}` : ''}`);
  }
  L.push('');

  // ── cards referencing missing facts
  L.push('## Cards that referenced missing facts', '');
  L.push('These card rows pointed at a fact the merged record does not have; the build dropped the row (the validator rejects dangling factRefs). Curators should add the fact or remove the row.', '');
  L.push(list(log.cardMissingFacts.map((c) => `${c.id}: "${esc(c.label)}" → facts.${c.fact}`)), '');
  if (log.comparisonRemaps.length) {
    L.push('### Comparison keys remapped', '');
    L.push(list(log.comparisonRemaps.map((c) => `${c.id} "${esc(c.label)}": compare.${c.from} → ${c.to === '(none)' ? 'no comparison line' : `compare.${c.to}`} (${c.why})`)), '');
  }

  // ── unresolved verify claims
  L.push('## Open verification items', '');
  L.push('Gathered from curator fact notes, auto-tier QA flags and stage confidence. Each is a number that ships but that a fact-checker should confirm or tighten before the P4 astronomer review signs off.', '');
  const verify: string[] = [];
  for (const o of objects.filter((x) => elig.has(x.id))) {
    for (const k of FACT_KEYS) {
      const f = o.facts[k];
      if (f?.note && UNCERTAIN.test(f.note) && (log.curatedFacts[o.id] ?? []).includes(k)) verify.push(`${o.id} facts.${k} = ${f.value} ${f.unit} [${f.sourceId}]: ${esc(f.note)}`);
    }
    if (o.kind === 'star' && o.stageConfidence === 'debated') verify.push(`${o.id}: evolutionary stage "${o.evolutionaryStage}" marked debated`);
  }
  L.push('### Curator notes flagging uncertainty', '');
  L.push(list(verify.sort(byString)), '');
  const autoOpen: string[] = [];
  for (const o of stars) {
    const flags = R.auto.starFlags[o.id] ?? [];
    const dFlag = flags.find((f) => /^distance-(needs-literature|uncertain)|gaia-rejected|L-R-Teff/.test(f));
    if (dFlag && !(log.curatedFacts[o.id] ?? []).includes('distanceLy') && o.facts.distanceLy) {
      autoOpen.push(`${o.id} (${o.names.display}): distanceLy ${o.facts.distanceLy.value} ly from ${o.facts.distanceLy.sourceId}; auto flag "${esc(dFlag)}" and no curated distance`);
    }
  }
  for (const q of R.auto.dsoQa) {
    if (q.issue !== 'curated-required' && q.issue !== 'no-age' && q.issue !== 'ned-few-primary') continue;
    const o = objects.find((x) => x.id === q.id);
    const cur = log.curatedFacts[q.id] ?? [];
    const covered = q.issue === 'no-age' ? cur.includes('ageMyr') : cur.includes('distanceLy') || cur.includes('ageMyr');
    if (!covered) autoOpen.push(`${q.id}${o ? ` (${o.names.display})` : ''}: dso.auto QA ${q.issue}: ${esc(q.detail)}`);
  }
  L.push('### Auto-tier QA flags the curated tier did not resolve', '');
  L.push(list(autoOpen.sort(byString)), '');

  // ── images
  L.push('## Image coverage', '');
  const withImg = objects.filter((o) => o.media.images.length);
  const featured = objects.filter((o) => o.media.images.some((i) => i.variant === 'featured' || i.variant === 'photo'));
  const licensed = objects.filter((o) => o.media.images.some((i) => i.src.startsWith('data/journey-images/licensed/')));
  L.push(table(['batch', 'objects', 'with ≥1 image', 'with a featured/photo image', 'licensed photo', 'eligible without image'], BATCH_IDS.map((b) => {
    const xs = objects.filter((o) => batchOf(o) === b);
    return [b, xs.length, xs.filter((o) => o.media.images.length).length,
      xs.filter((o) => o.media.images.some((i) => i.variant === 'featured' || i.variant === 'photo')).length,
      xs.filter((o) => o.media.images.some((i) => i.src.startsWith('data/journey-images/licensed/'))).length,
      xs.filter((o) => elig.has(o.id) && !o.media.images.length).length];
  })), '');
  L.push(`Overall: ${withImg.length}/${objects.length} objects have at least one image (${pct(withImg.length, objects.length)}); ${featured.length} have a featured/photo image; ${licensed.length} use a localised licensed photograph. Stars without photos fall back to the in-app visuals (spec decision 11): ${objects.filter((o) => !o.media.images.length && o.media.visuals.length).length} objects have visuals only, ${objects.filter((o) => !o.media.images.length && !o.media.visuals.length).length} have neither.`, '');
  const withLarge = objects.filter((o) => o.media.images.some((i) => i.large));
  L.push(`${log.images.filled.length} objects take their pictures from media.fill.json (binocular-field survey photos and showpiece photographs, fetch_media_fill.py); ${withLarge.length} objects have a large tap-to-enlarge copy.`, '');
  if (log.images.missingFile.length) {
    L.push('Images dropped because the file is not in client/public:', '', list(log.images.missingFile.map((x) => `${x.id}: ${x.src}`)), '');
  }
  if (log.images.remote.length) {
    L.push('Images still pointing at remote URLs (not yet localised by fetch_licensed_media.py):', '', list(log.images.remote.map((x) => `${x.id}: ${x.src}`)), '');
  }
  if (log.images.licensedSkipped.length) {
    L.push('Curated photographs dropped because the licence check skipped them:', '', list(log.images.licensedSkipped.map((x) => `${x.id}: ${x.src} (${esc(x.reason)})`)), '');
  }

  // ── merge log
  L.push('## Merge log', '');
  L.push('### Source registry', '');
  L.push('Canonical records and aliases live in `script/journeys/sources.canonical.json`. Rewrites applied (alias → canonical, count of records rewritten):', '');
  L.push(list(Object.entries(log.sourceRewrites).sort((a, b) => byString(a[0], b[0])).map(([k, n]) => `${k} (${n})`)), '');
  L.push(`Sources defined but cited by nothing after the merge (not shipped): ${log.unreferencedSources.length ? log.unreferencedSources.sort(byString).join(', ') : 'none'}.`, '');
  L.push('### Merge-layer fixes (curated/_fixes.json)', '');
  L.push(list(log.fixesApplied.map((f) => `${f.id}: ${f.what}${f.why ? ` — ${esc(f.why)}` : ''}`)), '');
  L.push('### Contexts', '');
  L.push(list([
    ...log.contexts.merged.map((m) => `${m.id}: duplicate records merged from ${m.files.join(', ')}`),
    ...log.contexts.addedByFix.map((m) => `${m.id}: member ${m.member} added (fix)`),
    ...log.contexts.unknownMembers.map((m) => `${m.id}: unknown member ${m.member} dropped`),
  ]), '');
  const mirrored = countBy(log.contexts.mirrored, (m) => `${m.id} (${m.dir})`);
  L.push(`Membership links mirrored so that object.contextIds and context.memberIds agree: ${Array.from(mirrored).map(([k, n]) => `${k} ×${n}`).join(', ') || 'none'}.`, '');
  L.push('### Narration', '');
  L.push(`Added from script/journeys/kb/narration-extra.json: ${log.narration.added.length ? log.narration.added.join(', ') : 'none'}.`, '');
  L.push(`Keys defined by more than one curated file (variants unioned): ${log.narration.unioned.map((u) => `${u.key} (${u.variants} variants)`).join(', ') || 'none'}.`, '');
  L.push(`Edge transition keys pruned because no shipped edge uses them: ${log.narration.pruned.length ? log.narration.pruned.join(', ') : 'none'}.`, '');
  L.push('### Other repairs and notes', '');
  L.push(list([
    ...log.dropped.map((d) => `${d.id}: dropped ${d.what} (${d.why})`),
    ...log.magConflicts.map((m) => `${m.id}: curated mag ${m.curated} differs from auto ${m.auto} (auto kept)`),
    ...log.autoOnly.map((id) => `${id}: no curated record (ships as auto-only, never in journeys)`),
    ...log.seeds.unknownStops.map((s) => `story seed ${s.seed}: stop ${s.stop} is not a KB object`),
    ...log.notes,
  ]), '');
  const nameDiff = R.list.map((e) => ({ e, o: objects.find((x) => x.id === e.id)! }))
    .filter(({ e, o }) => o && norm(e.name) !== norm(o.names.display) && !norm(e.name).includes(norm(o.names.display)) && !norm(o.names.display).includes(norm(e.name)));
  L.push('### Display names that differ from object-list.json', '');
  L.push('Not errors (curators chose the display name); listed so naming stays deliberate.', '');
  L.push(list(nameDiff.map(({ e, o }) => `${e.id}: list "${esc(e.name)}" → KB "${esc(o.names.display)}"`)), '');
  return `${L.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

const norm = (s: string) => s.toLowerCase().normalize('NFKD').replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
