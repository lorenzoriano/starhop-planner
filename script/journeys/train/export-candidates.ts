export const LEVELS = ['first-night', 'curious', 'keen'] as const;
export const START_KINDS = ['dusk+30', '22:30', '01:30'] as const;

export interface Conditions {
  id: string;
  site: (typeof SITES)[number]['name'];
  lat: number; lon: number; tz: string;
  date: string; month: number;
  startKind: (typeof START_KINDS)[number];
  instant: string;
  instrument: (typeof INSTRUMENTS)[number];
  sky: number;
  level: (typeof LEVELS)[number];
}

/** Seeded Latin hypercube: each dimension's strata are visited evenly across the n samples. */
export function sampleConditions(n: number, seed: number): Conditions[] {
  const rng = mulberry32(seed);
  const dims = [SITES.length, 24, START_KINDS.length, INSTRUMENTS.length, SKIES.length, LEVELS.length];
  const perms = dims.map((k) => seededShuffle(Array.from({ length: n }, (_, i) => Math.floor((i * k) / n)), rng));
  const out: Conditions[] = [];
  for (let i = 0; i < n; i++) {
    const site = SITES[perms[0][i]];
    const d = perms[1][i];
    const month = Math.floor(d / 2) + 1;
    const day = d % 2 ? 22 : 8;
    const date = `2027-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
    const startKind = START_KINDS[perms[2][i]];
    const instant = startInstant(site, date, startKind);
    if (!instant) continue;
    out.push({
      id: `c${String(i).padStart(4, '0')}`,
      site: site.name, lat: site.lat, lon: site.lon, tz: site.tz,
      date, month, startKind, instant,
      instrument: INSTRUMENTS[perms[3][i]],
      sky: SKIES[perms[4][i]],
      level: LEVELS[perms[5][i]],
    });
  }
  return out;
}

function startInstant(site: (typeof SITES)[number], date: string, kind: (typeof START_KINDS)[number]): string | null {
  if (kind === '22:30') return fromZonedTime(`${date}T22:30:00`, site.tz).toISOString();
  if (kind === '01:30') return new Date(fromZonedTime(`${date}T01:30:00`, site.tz).getTime() + 86_400_000).toISOString();
  const noon = fromZonedTime(`${date}T12:00:00`, site.tz);
  const obs = new Astro.Observer(site.lat, site.lon, 0);
  for (const alt of [-18, -12]) {
    const t = Astro.SearchAltitude(Astro.Body.Sun, obs, -1, noon, 1, alt);
    if (t) return new Date(t.date.getTime() + 30 * 60_000).toISOString();
  }
  return null;
}

// ───────────────────────────── KB loading ─────────────────────────────

async function loadKb(which: string | undefined): Promise<{ kb: KnowledgeBase; label: string }> {
  const dir = which && !['fixture', 'synthetic'].includes(which) ? resolve(which) : join(ROOT, 'client/public/data/journeys');
  if (which === 'synthetic') {
    return { kb: syntheticKb(12), label: 'synthetic-12' };
  }
  if (which !== 'fixture' && existsSync(join(dir, 'kb.json'))) {
    const read = (f: string) => JSON.parse(readFileSync(join(dir, f), 'utf8'));
    return {
      kb: knowledgeBaseFromFiles({ kb: read('kb.json'), concepts: read('concepts.json'), edges: read('edges.json'), templates: read('templates.json'), narration: read('narration.json'), lenses: existsSync(join(dir, 'lenses.json')) ? read('lenses.json') : undefined }),
      label: dir,
    };
  }
  return { kb: FIXTURE_KB, label: 'fixture' };
}

// ───────────────────────────── judge rendering ─────────────────────────────

/** What a judge sees (doc 05 §7.3.3): no scores, no features, no archetype id. */
export function renderForJudges(j: Journey, nar: JourneyNarration, kb: KnowledgeBase, c: Conditions, moonPct: number): string {
  const byId = new Map(kb.objects.map((o) => [o.id, o] as const));
  const local = formatInTimeZone(new Date(c.instant), c.tz, 'yyyy-MM-dd HH:mm');
  const lines: string[] = [
    `## ${nar.title.text}`,
    `*${nar.drivingQuestion.text}*  ${nar.hook.text}`,
    '',
    `Conditions: ${c.site} (lat ${c.lat}°), start ${local} local, ${c.instrument.label} binoculars (${c.instrument.fovDeg}° field), sky ${c.sky} mag/arcsec², Moon ${moonPct}% lit${moonPct ? '' : ' or down'}, observer level: ${c.level}. About ${j.durationMin} minutes, ${j.stops.length} stops, ${j.difficulty}.`,
    '',
    '| # | Object | Role | Alt | Hop | Binocular |',
    '|---|--------|------|-----|-----|-----------|',
  ];
  j.stops.forEach((s, i) => {
    const o = byId.get(s.objectId)!;
    lines.push(`| ${i + 1} | ${o.names.display} | ${s.role} | ${Math.round(s.altAtStart)}° | ${i ? `${s.getThere.distanceDeg}° (${s.getThere.fields} fields)` : '—'} | ${s.challenge ? 'challenge' : 'ok'} |`);
  });
  lines.push('');
  j.stops.forEach((s, i) => {
    const o = byId.get(s.objectId)!;
    const sn = nar.stops[i];
    const fact = sn.numbers[0];
    lines.push(`**${i + 1}. ${o.names.display}** — ${sn.whyHere.text}${sn.bridge ? ` ${sn.bridge.text}` : ''}`);
    if (sn.transition) lines.push(`- From the last stop: ${sn.transition.text}`);
    lines.push(`- Getting there: ${s.getThere.bearingText}`);
    if (fact) lines.push(`- ${fact.label}: ${fact.value}${fact.comparison ? `. ${fact.comparison.text}` : ''}`);
  });
  if (nar.payoff) lines.push('', `Payoff: ${nar.payoff.text}`);
  return lines.join('\n');
}

// ───────────────────────────── slates ─────────────────────────────

/** 2 best by heuristic, 2 from the middle, 1 seeded-random, 1 weakest (doc 05 §7.3.2). */
export function pickSlate<T extends { h: number; key: string }>(pool: T[], rng: () => number): T[] {
  const sorted = pool.slice().sort((a, b) => b.h - a.h || a.key.localeCompare(b.key));
  if (sorted.length <= 6) return sorted;
  const picked = new Set<number>([0, 1]);
  const mid = Math.floor(sorted.length / 2);
  picked.add(mid - 1); picked.add(mid);
  picked.add(sorted.length - 1);
  const rest = sorted.map((_, i) => i).filter((i) => !picked.has(i));
  picked.add(rest[Math.floor(rng() * rest.length)]);
  return Array.from(picked).sort((a, b) => a - b).map((i) => sorted[i]);
}

// ───────────────────────────── main ─────────────────────────────

export async function main(): Promise<void> {
  if (flag('meta-only')) {
    const p = join(HERE, 'feature-meta.json');
    writeFileSync(p, `${JSON.stringify(featureMeta(), null, 2)}\n`);
    console.log(`wrote ${p}`);
    return;
  }
  const n = Number(arg('n', '300'));
  const seed = Number(arg('seed', '7'));
  const minSlate = Number(arg('min-slate', '3'));
  const outDir = resolve(arg('out', join(ROOT, 'data-dev/journeys-training'))!);
  mkdirSync(outDir, { recursive: true });
  const { kb, label } = await loadKb(arg('kb'));
  const conditions = sampleConditions(n, seed);
  const cand: string[] = [];
  const slates: string[] = [];
  let journeysTotal = 0, slateCount = 0;

  for (const c of conditions) {
    const req: JourneyRequest = {
      instant: c.instant, lat: c.lat, lon: c.lon, timezone: c.tz,
      instrument: { fovDeg: c.instrument.fovDeg, aperture: c.instrument.aperture, magnification: c.instrument.magnification, ...('stabilized' in c.instrument ? { stabilized: true } : {}) },
      skyBrightness: c.sky, level: c.level,
    };
    const extra = new Map<string, { criteria: Doc04Criteria; features: number[]; moon: number }>();
    const scorer: JourneyScorer = (x) => {
      const input = featureInputFromScoring(x);
      const features = computeFeatures(input);
      extra.set(x.journey.key, { criteria: computeCriteria(input, { minAlt: x.table.s.minAlt, kbObjects: x.kb.objects }), features, moon: input.moonIllumination });
      return { score: x.heuristic, features, scorer: 'heuristic' };
    };
    let pool;
    try {
      pool = generatePool(kb, req, { explore: true, scorer });
    } catch (err) {
      console.warn(`${c.id}: engine error ${(err as Error).message}`);
      continue;
    }
    journeysTotal += pool.journeys.length;
    const byPatch = new Map<string, Journey[]>();
    for (const j of pool.journeys) {
      const k = `${j.regionCenter.label}|${j.regionCenter.ra.toFixed(0)}|${j.regionCenter.dec.toFixed(0)}`;
      (byPatch.get(k) ?? byPatch.set(k, []).get(k)!).push(j);
    }
    // Slates per (conditions, patch); journeys from patches too thin for a slate are pooled into one mixed
    // slate for the same night (still a fair comparison: same sky, site, binoculars and observer).
    const groups = Array.from(byPatch.entries()).sort((a, b) => a[0].localeCompare(b[0]));
    const leftovers = groups.filter(([, js]) => js.length < minSlate).flatMap(([, js]) => js);
    const usable = groups.filter(([, js]) => js.length >= minSlate);
    if (leftovers.length >= minSlate) usable.push(['mixed', leftovers]);
    let p = 0;
    for (const [patchKey, js] of usable) {
      const rng = rngFor(String(seed), c.id, patchKey);
      const slate = pickSlate(js.map((j) => ({ j, h: j.score, key: j.key })), rng).map((x) => x.j);
      const slateId = `${c.id}-p${p++}`;
      const items: Record<string, string> = {};
      for (const j of slate) {
        const ex = extra.get(j.key)!;
        const { journey, narration } = narrateAndApply(j, kb, { seedKey: pool.seedKey, region: j.regionCenter.label, moonIllumination: ex.moon });
        const moonPct = Math.round(ex.moon * 100);
        items[j.key] = renderForJudges(journey, narration, kb, c, moonPct);
        cand.push(JSON.stringify({
          slateId, patch: patchKey, splitKey: `${c.site}|${c.month}`, site: c.site, month: c.month, conditions: c,
          journeyKey: j.key, templateId: j.templateId, features: ex.features, criteria: ex.criteria,
          scores: { engineH: j.score, featureHeuristic: scoreJourney(ex.features, HEURISTIC_MODEL), doc04Q: doc04Quality(ex.criteria) },
          kbVersion: kb.version, journey,
        }));
      }
      const order = seededShuffle(Object.keys(items), rngFor(String(seed), slateId, 'order'));
      slates.push(JSON.stringify({ slateId, conditions: c, items, orders: [order, order.slice().reverse()] }));
      slateCount++;
    }
  }
  writeFileSync(join(outDir, 'candidates.jsonl'), cand.join('\n') + (cand.length ? '\n' : ''));
  writeFileSync(join(outDir, 'slates.jsonl'), slates.join('\n') + (slates.length ? '\n' : ''));
  writeFileSync(join(outDir, 'feature-meta.json'), `${JSON.stringify(featureMeta(), null, 2)}\n`);
  console.log(`kb=${label} conditions=${conditions.length} journeys=${journeysTotal} slates=${slateCount} rows=${cand.length} → ${outDir}`);
}
