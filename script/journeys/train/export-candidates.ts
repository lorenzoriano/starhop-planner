/**
 * Sky Journeys learned scorer, step 1: dump candidate journeys + features for judge slates (doc 05 §7.3).
 *
 * Run from the repository root through the CommonJS launcher (tsx's ESM mode cannot see astronomy-engine's
 * CJS exports, so the engine must load as CJS):
 *
 *   npx tsx script/journeys/train/run-export.cts --meta-only
 *       writes script/journeys/train/feature-meta.json (feature names, clip ranges, monotone constraints,
 *       groups, hash, heuristic weights) — the single source train.py reads, generated from features.ts.
 *   npx tsx script/journeys/train/run-export.cts [--kb <dir>|fixture|synthetic] [--n 300] [--seed 7]
 *       [--out data-dev/journeys-training] [--min-slate 3]
 *       samples observing conditions (seeded Latin hypercube over sites × dates × start times × binoculars ×
 *       sky × level), runs the REAL engine (assemble.ts generatePool, explore mode: whole valid pool, no MMR),
 *       computes the 36 features with the same features.ts used at runtime, groups journeys by patch into
 *       slates of up to 6 (2 best by heuristic, 2 middle, 1 random, 1 weakest valid), and writes
 *         candidates.jsonl  one row per slate member: features, doc 04 criteria, baseline scores, full journey
 *         slates.jsonl      judge-facing slates: rendered text per journey, plus two orders (shuffled, reversed)
 *
 * Every slate member passed the engine's validator, so judges only compare valid journeys (doc 05 §7.3.2).
 */
